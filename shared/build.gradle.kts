kotlin {
    compilerOptions {
        freeCompilerArgs.add("-Xexpect-actual-classes")
        // Zero today; as errors they stay zero (a deprecation is a migration someone has to do).
        allWarningsAsErrors.set(true)
    }

    android {
        namespace = "dev.idoodler.labimporter.core"
        compileSdk = 37
        minSdk = 26
        compilerOptions { jvmTarget.set(JvmTarget.JVM_17) }
    }

    // Host JVM target: only used to run the shared unit tests fast, against
    // the real loinc.db (the bundled SQLite driver ships macOS/Linux natives).
    jvm()

    // The iOS app links this as the static `LabImporterCore` framework: Xcode's
    // "Build shared Kotlin" phase runs `embedAndSignAppleFrameworkForXcode`
    // (an XCFramework is also available via
    // `assembleLabImporterCoreReleaseXCFramework`). SKIE bridges suspend
    // functions/Flows to Swift async/AsyncSequence.
    val xcf = XCFramework("LabImporterCore")
    listOf(iosArm64(), iosSimulatorArm64()).forEach { target ->
        target.binaries.framework {
            baseName = "LabImporterCore"
            isStatic = true
            binaryOption("bundleId", "dev.idoodler.labimporter.core")
            xcf.add(this)
        }
    }

    sourceSets {
        all {
            languageSettings.optIn("kotlin.uuid.ExperimentalUuidApi")
            languageSettings.optIn("kotlin.time.ExperimentalTime")
        }
        commonMain.dependencies {
            implementation(libs.kotlinx.coroutines.core)
            implementation(libs.kotlinx.serialization.json)
            api(libs.kotlinx.datetime)
            api(libs.androidx.sqlite)
            implementation(libs.xmlutil.core)
        }
        // Android/JVM bundle SQLite so FTS5 is guaranteed on every OS version;
        // iOS uses the system SQLite (which ships FTS5) to avoid a second copy.
        androidMain.dependencies { implementation(libs.androidx.sqlite.bundled) }
        jvmMain.dependencies { implementation(libs.androidx.sqlite.bundled) }
        iosMain.dependencies { implementation(libs.androidx.sqlite.framework) }
        commonTest.dependencies {
            implementation(kotlin("test"))
        }
    }
}

// SKIE would otherwise try to upload anonymous build analytics; this project
// makes no network calls it doesn't need.
skie {
    analytics {
        disableUpload.set(true)
        enabled.set(false)
    }
}

tasks.withType<Test>().configureEach {
    // Tests that need the catalog read it from the build-generated loinc.db.
    systemProperty("loinc.db", rootProject.layout.buildDirectory.file("loinc/loinc.db").get().asFile.absolutePath)
    systemProperty("golden.dir", layout.projectDirectory.dir("src/jvmTest/golden").asFile.absolutePath)
    // ./gradlew :shared:jvmTest -Pgolden.record=true rewrites the golden files.
    systemProperty("golden.record", providers.gradleProperty("golden.record").getOrElse("false"))
    // CI shows only the log: print a failure's message, causes and stack, not just its type and line.
    testLogging {
        events(org.gradle.api.tasks.testing.logging.TestLogEvent.FAILED)
        exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
        showExceptions = true
        showCauses = true
        showStackTraces = true
    }
}

// Line and branch coverage of the JVM tests (`koverXmlReport`), for orientation only:
// docs/quality/RUBRIC.md scores the mutation score, not coverage, so there is no minimum.
kover {
    reports {
        filters {
            // Generated by kotlinx.serialization: no logic of ours to cover.
            excludes { classes("*\$\$serializer") }
        }
    }
}

/*
 * Mutation testing with PIT (tools/quality/mutation.sh): changes the compiled code
 * one small way at a time and checks a JVM test fails. Run on demand or on a
 * schedule, never as part of `check` — it takes minutes, not seconds.
 */
val pitest: Configuration = configurations.create("pitest") {
    isCanBeConsumed = false
    isCanBeResolved = true
}
dependencies { pitest(libs.pitest.command.line) }

val jvmTestRuntime: FileCollection = kotlin.jvm().compilations.getByName("test").let { test ->
    test.output.allOutputs + kotlin.jvm().compilations.getByName("main").output.allOutputs + test.runtimeDependencyFiles!!
}

tasks.register<JavaExec>("mutationTest") {
    group = "verification"
    description = "PIT mutation testing of export, parse, model and loinc against the JVM tests."
    dependsOn("jvmTestClasses", ":androidApp:copyLoincForTests")
    classpath = pitest + jvmTestRuntime
    mainClass.set("org.pitest.mutationtest.commandline.MutationCoverageReport")
    val core = "dev.idoodler.labimporter.core"
    val reportDir = rootProject.layout.buildDirectory.dir("quality/mutation").get().asFile.absolutePath
    val loincDb = rootProject.layout.buildDirectory.file("loinc/loinc.db").get().asFile.absolutePath
    val goldenDir = layout.projectDirectory.dir("src/jvmTest/golden").asFile.absolutePath
    val sources = listOf("src/commonMain/kotlin", "src/jvmMain/kotlin").map { layout.projectDirectory.dir(it).asFile.absolutePath }
    // `-Pmutation.classes=…` narrows the run (comma-separated globs), e.g. to one class while writing tests.
    val targets = providers.gradleProperty("mutation.classes").orElse(
        listOf("export", "parse", "model", "loinc").joinToString(",") { "$core.$it.*" } + ",$core.platform.NumberFormatting*",
    )
    val threads = providers.gradleProperty("mutation.threads").orElse("2")
    outputs.dir(reportDir)
    // Always reruns: its inputs are every test and every class, and it is only run on purpose.
    outputs.upToDateWhen { false }
    argumentProviders += CommandLineArgumentProvider {
        listOf(
            "--targetClasses=${targets.get()}",
            "--targetTests=$core.*",
            "--sourceDirs=${sources.joinToString(",")}",
            "--reportDir=$reportDir",
            "--outputFormats=XML,HTML",
            "--timestampedReports=false",
            "--threads=${threads.get()}",
            // Kotlin's generated members: a mutant in `equals` or `component1` says nothing about our code.
            "--excludedClasses=*\$\$serializer",
            "--excludedMethods=equals,hashCode,toString,copy,copy\$default,component*,write\$Self*",
            // Calls Kotlin inserts: parameter null checks, and the Int overflow guards of `forEachIndexed`
            // and `count` (shared/ calls no in-place collection function, so nothing of ours is skipped).
            "--avoidCallsTo=kotlin.jvm.internal.Intrinsics,kotlin.collections.CollectionsKt",
            "--jvmArgs=-Xmx768m,-Dloinc.db=$loincDb,-Dgolden.dir=$goldenDir,-Dgolden.record=false",
        )
    }
}

