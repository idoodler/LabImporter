#!/usr/bin/env python3
"""Generate the Android adaptive (layered) launcher icon from the iOS icon art.

The iOS icon (LabImporter/AppIcon.icon) is three layers — report card, result
rows, heart. Android adaptive icons have a background and a foreground layer
(plus a monochrome layer for themed icons), which launchers mask to the user's
icon shape and move independently for parallax/press effects. So:

  background  gradient + soft card shadow + report card + rows
  foreground  the heart with a soft glow (it floats over the card)
  monochrome  card-with-cut-out-rows + heart silhouette (Material You themed icons)

Each layer has a light and a dark (night) variant mirroring the iOS
appearances. Geometry is the iOS 1024-unit artwork, scaled so the whole
composition stays inside the adaptive icon's 66dp safe zone.

Usage: tools/generate_android_icon.py [--preview DIR]
  --preview  also writes SVG previews (circle + squircle masks) to DIR
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "androidApp", "src", "main", "res")

# Artwork (iOS AppIcon.icon/Assets, 1024 canvas).
CARD = (193, 170, 440, 540, 76)
ROWS = [(265, 264, 296, 48, 24), (265, 360, 210, 48, 24), (265, 456, 150, 48, 24)]
HEART = ("M 627.0 838.8 C 577.0 802.0 441.0 718.0 441.0 612.0 C 441.0 544.0 489.0 494.0 543.0 494.0 "
         "C 591.0 494.0 623.0 522.0 641.0 560.0 C 659.0 522.0 691.0 494.0 739.0 494.0 "
         "C 793.0 494.0 841.0 544.0 841.0 612.0 C 841.0 718.0 705.0 802.0 655.0 838.8 Q 641.0 850.0 627.0 838.8 Z")

# Map the artwork's centre (517, 510) to the canvas centre and scale it to
# ~47% of the 108dp canvas, which keeps every corner inside the safe circle.
SCALE = 0.71
PIVOT = (517, 510)

PALETTES = {
    "light": dict(bg=("#FFFFFF", "#ECF0F6"), card=("#4C82FF", "#2459F0"), rows="#FFFFFF",
                  heart=("#FF7896", "#FF1E50"), glow="#FF1E50", shadow="#1A2F6BFF"),
    "night": dict(bg=("#1F2C52", "#0C1124"), card=("#4A7BF0", "#2A55D6"), rows="#E1ECFF",
                  heart=("#FF82A0", "#FF2D5F"), glow="#FF2D5F", shadow="#40000000"),
}


def rrect(x, y, w, h, r):
    return (f"M{x + r},{y}h{w - 2 * r}a{r},{r} 0 0 1 {r},{r}v{h - 2 * r}a{r},{r} 0 0 1 {-r},{r}"
            f"h{-(w - 2 * r)}a{r},{r} 0 0 1 {-r},{-r}v{-(h - 2 * r)}a{r},{r} 0 0 1 {r},{-r}z")


def group_open(scale: float = SCALE) -> str:
    tx, ty = 512 - PIVOT[0], 512 - PIVOT[1]
    return (f'    <group android:pivotX="{PIVOT[0]}" android:pivotY="{PIVOT[1]}" android:scaleX="{scale}" '
            f'android:scaleY="{scale}" android:translateX="{tx}" android:translateY="{ty}">\n')


def linear(path, colors, y0, y1, x=512):
    return (f'        <path android:pathData="{path}">\n'
            f'            <aapt:attr name="android:fillColor">\n'
            f'                <gradient android:type="linear" android:startX="{x}" android:startY="{y0}" android:endX="{x}" android:endY="{y1}">\n'
            f'                    <item android:offset="0" android:color="{colors[0]}" />\n'
            f'                    <item android:offset="1" android:color="{colors[1]}" />\n'
            f'                </gradient>\n'
            f'            </aapt:attr>\n'
            f'        </path>\n')


def radial(path, color_center, cx, cy, r):
    return (f'        <path android:pathData="{path}">\n'
            f'            <aapt:attr name="android:fillColor">\n'
            f'                <gradient android:type="radial" android:centerX="{cx}" android:centerY="{cy}" android:gradientRadius="{r}">\n'
            f'                    <item android:offset="0" android:color="{color_center}" />\n'
            f'                    <item android:offset="1" android:color="#00000000" />\n'
            f'                </gradient>\n'
            f'            </aapt:attr>\n'
            f'        </path>\n')


HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- GENERATED by tools/generate_android_icon.py — edit the script, not this file. -->\n'
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    xmlns:aapt="http://schemas.android.com/aapt"\n'
          '    android:width="108dp" android:height="108dp"\n'
          '    android:viewportWidth="1024" android:viewportHeight="1024">\n')
FULL = "M0,0h1024v1024h-1024z"


def background(p) -> str:
    x, y, w, h, r = CARD
    out = HEADER + linear(FULL, p["bg"], 0, 716)
    out += group_open()
    # Soft lift under the card.
    out += radial(rrect(x - 60, y - 20, w + 120, h + 140, r + 60), p["shadow"], x + w / 2, y + h / 2 + 50, 420)
    out += linear(rrect(*CARD), p["card"], y, y + h)
    for row in ROWS:
        out += f'        <path android:fillColor="{p["rows"]}" android:pathData="{rrect(*row)}" />\n'
    return out + "    </group>\n</vector>\n"


def foreground(p) -> str:
    out = HEADER + group_open()
    # A pink glow so the heart reads as floating above the card.
    out += radial("M391,444h500v460h-500z", p["glow"][:1] + "55" + p["glow"][1:], 641, 690, 250)
    out += linear(HEART, p["heart"], 494, 850)
    return out + "    </group>\n</vector>\n"


def art(p) -> str:
    """Background-free composite for in-app use (onboarding, empty states)."""
    x, y, w, h, r = CARD
    out = HEADER + group_open(1.3)  # fills its own canvas: no adaptive-icon safe zone in-app
    out += linear(rrect(*CARD), p["card"], y, y + h)
    for row in ROWS:
        out += f'        <path android:fillColor="{p["rows"]}" android:pathData="{rrect(*row)}" />\n'
    out += linear(HEART, p["heart"], 494, 850)
    return out + "    </group>\n</vector>\n"


def monochrome() -> str:
    rows = "".join(rrect(*row) for row in ROWS)
    out = HEADER + group_open()
    out += f'        <path android:fillColor="#000000" android:fillType="evenOdd" android:pathData="{rrect(*CARD)}{rows}" />\n'
    out += f'        <path android:fillColor="#000000" android:pathData="{HEART}" />\n'
    return out + "    </group>\n</vector>\n"


def write(rel: str, text: str) -> None:
    path = os.path.join(RES, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def svg_preview(p, mask: str) -> str:
    """Approximate launcher rendering: background + foreground under a mask."""
    x, y, w, h, r = CARD
    tx, ty = 512 - PIVOT[0], 512 - PIVOT[1]
    g = f'<g transform="translate({512},{512}) scale({SCALE}) translate({-PIVOT[0]},{-PIVOT[1]}) translate({tx / SCALE},{ty / SCALE})">'
    rows = "".join(f'<path fill="{p["rows"]}" d="{rrect(*row)}"/>' for row in ROWS)
    clip = ('<circle cx="512" cy="512" r="341"/>' if mask == "circle"
            else '<rect x="171" y="171" width="682" height="682" rx="190"/>')
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 1024 1024">
<defs>
<clipPath id="m">{clip}</clipPath>
<linearGradient id="bg" x1="0" y1="0" x2="0" y2="716" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{p['bg'][0]}"/><stop offset="1" stop-color="{p['bg'][1]}"/></linearGradient>
<linearGradient id="card" x1="0" y1="{y}" x2="0" y2="{y + h}" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{p['card'][0]}"/><stop offset="1" stop-color="{p['card'][1]}"/></linearGradient>
<linearGradient id="heart" x1="0" y1="494" x2="0" y2="850" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{p['heart'][0]}"/><stop offset="1" stop-color="{p['heart'][1]}"/></linearGradient>
<radialGradient id="glow" cx="641" cy="690" r="250" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{p['glow']}" stop-opacity="0.33"/><stop offset="1" stop-color="{p['glow']}" stop-opacity="0"/></radialGradient>
</defs>
<rect width="1024" height="1024" fill="#808080"/>
<g clip-path="url(#m)">
<rect width="1024" height="1024" fill="url(#bg)"/>
{g}<path fill="url(#card)" d="{rrect(*CARD)}"/>{rows}<rect x="391" y="444" width="500" height="460" fill="url(#glow)"/><path fill="url(#heart)" d="{HEART}"/></g>
</g></svg>"""


def main() -> int:
    for variant, folder in (("light", "drawable"), ("night", "drawable-night")):
        p = PALETTES[variant]
        write(f"{folder}/ic_launcher_background.xml", background(p))
        write(f"{folder}/ic_launcher_foreground.xml", foreground(p))
        write(f"{folder}/ic_launcher_foreground_art.xml", art(p))
    write("drawable/ic_launcher_monochrome.xml", monochrome())
    if "--preview" in sys.argv:
        out = sys.argv[sys.argv.index("--preview") + 1]
        os.makedirs(out, exist_ok=True)
        for variant in PALETTES:
            for mask in ("circle", "squircle"):
                with open(os.path.join(out, f"icon-{variant}-{mask}.svg"), "w") as fh:
                    fh.write(svg_preview(PALETTES[variant], mask))
    print("Android launcher icon layers written to", RES)
    return 0


if __name__ == "__main__":
    sys.exit(main())
